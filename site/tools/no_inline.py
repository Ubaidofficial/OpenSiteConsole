"""Move every inline style="..." in site/index.html into generated classes in styles.css.
Run from the repository root: python3 site/tools/no_inline.py (after editing the page; running it again changes nothing).
The page's Content-Security-Policy (style-src 'self') blocks style attributes, so per-element values (bar widths, delays,
positions) must live in the stylesheet. Each distinct declaration list becomes one class, named from its content.
Rules already generated are kept as long as the page still uses their class."""
import hashlib, re

h = 'site/index.html'
c = 'site/assets/styles.css'
html = open(h).read()
css = open(c).read()
START, END = '/* ── generated by site/tools/no_inline.py: values that used to be inline styles (CSP forbids style attributes) ── */', '/* ── end generated ── */'

rules = {}
if START in css:
    block = css[css.index(START) + len(START):css.index(END)]
    for m in re.finditer(r'^\.(v-[a-z0-9_]+) \{ (.*); \}$', block, re.M):
        rules[m.group(1)] = m.group(2)

def name_for(decl):
    # readable when it is one custom property (e.g. "v-w24p" for --w:24%), hashed otherwise
    m = re.fullmatch(r'--([a-z]+):\s*([0-9.]+)(%?)', decl)
    if m:
        return f'v-{m.group(1)}{m.group(2).replace(".", "_")}' + ('p' if m.group(3) else '')
    return 'v-' + hashlib.sha1(decl.encode()).hexdigest()[:7]

def fix_tag(m):
    tag = m.group(0)
    sm = re.search(r'\sstyle="([^"]*)"', tag)
    decl = sm.group(1).strip().rstrip(';')
    cls = name_for(decl)
    rules[cls] = decl
    tag = tag.replace(sm.group(0), '')
    if re.search(r'\sclass="', tag):
        return re.sub(r'\sclass="([^"]*)"', lambda k: f' class="{(k.group(1) + " " + cls).strip()}"', tag, count=1)
    return re.sub(r'^<([a-zA-Z0-9]+)', lambda k: f'<{k.group(1)} class="{cls}"', tag, count=1)

html = re.sub(r'<[a-zA-Z][^<>]*\sstyle="[^"]*"[^<>]*>', fix_tag, html)
used = set(re.findall(r'\bv-[a-z0-9_]+\b', html))
keep = {k: v for k, v in rules.items() if k in used}
missing = sorted(u for u in used if u not in keep)
if missing:
    raise SystemExit(f'classes used by the page with no rule: {missing}')
gen = START + '\n' + '\n'.join(f'.{k} {{ {v}; }}' for k, v in sorted(keep.items())) + '\n' + END
css = css[:css.index(START)] + gen + css[css.index(END) + len(END):] if START in css else css.rstrip('\n') + '\n\n' + gen + '\n'
open(h, 'w').write(html)
open(c, 'w').write(css)
print(len(keep), 'rules')
