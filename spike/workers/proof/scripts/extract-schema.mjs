#!/usr/bin/env node
/**
 * Builds the D1 migration files for the proof FROM THE REAL src/lib/server/db.ts (nothing is retyped):
 *   migrations/0001_schema_slice.sql  the verbatim CREATE TABLE / CREATE INDEX statements for the tables in SLICE
 *   migrations/0002_added_columns.sql the ALTER TABLE ... ADD COLUMN lines from migrate(), for the same tables
 *
 * Why two files: db.ts creates tables and then, on every boot, probes `PRAGMA table_info` and ALTERs in missing columns.
 * D1 migrations are numbered one-shot files, so the probe-and-alter pattern becomes a plain migration file.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = readFileSync(path.resolve(here, '../../../../src/lib/server/db.ts'), 'utf8');
const SLICE = ['accounts', 'sites', 'site_daily', 'site_daily_type', 'site_appearance', 'sa_rows', 'sync_runs', 'kv'];

const schema = /const SCHEMA = `([\s\S]*?)`;/.exec(src)[1];
// Statements end with ';' at end of line (comments inside statements contain no ';' followed by newline).
const stmts = schema.split(/;\s*\n/).map((s) => s.trim()).filter(Boolean).map((s) => s + ';');
const keep = stmts.filter((s) => {
	const m = /^CREATE (?:UNIQUE )?(?:TABLE|INDEX) IF NOT EXISTS (\w+)(?: ON (\w+))?/.exec(s);
	if (!m) return false;
	const table = m[2] ?? m[1];
	return SLICE.includes(table);
});
const alters = [...src.matchAll(/if \(!cols\('(\w+)'\)\.includes\('(\w+)'\)\) db\.exec\((["'`])(ALTER TABLE .*?)\3\)/g)]
	.filter((m) => SLICE.includes(m[1]))
	.map((m) => m[4] + ';');

mkdirSync(path.resolve(here, '../migrations'), { recursive: true });
writeFileSync(path.resolve(here, '../migrations/0001_schema_slice.sql'), `-- Generated by scripts/extract-schema.mjs from src/lib/server/db.ts. Do not edit.\n${keep.join('\n')}\n`);
writeFileSync(path.resolve(here, '../migrations/0002_added_columns.sql'), `-- Generated by scripts/extract-schema.mjs from migrate() in src/lib/server/db.ts. Do not edit.\n${alters.join('\n')}\n`);
console.log(`${keep.length} CREATE statements, ${alters.length} ALTERs`);
